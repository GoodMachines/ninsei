"""Write ui/05_media.js: the Lobby's empty-state art as an inline WebP data URI.

The art is generated (gpt-image-2 via Codex; docs/media/src/lobby-art.jpg). Inline, because Desktop reaches
the backend only through JSON calls, so an <img> can't load it from a plugin route. Hermes's install scanner
reads an inline base64 run that decodes to an image header as media, not as an encoded payload.
Needs ImageMagick with WebP. Usage: python scripts/build_media.py [--check]"""
import base64
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/media/src/lobby-art.jpg"
OUT = ROOT / "ui/05_media.js"
WIDTH = 480  # shown at up to 240 css px, so sharp on 2x screens


def render() -> str:
    webp = subprocess.run(["magick", str(SRC), "-resize", f"{WIDTH}x", "-strip", "-define", "webp:method=6",
                           "-quality", "78", "webp:-"], capture_output=True, check=True).stdout
    b64 = base64.b64encode(webp).decode("ascii")
    return ("// Generated by scripts/build_media.py from docs/media/src/lobby-art.jpg. Do not edit.\n"
            "// The Lobby's empty state: the banner's rainy street with nobody there yet but one agent, waiting.\n"
            f"const LOBBY_ART = 'data:image/webp;base64,{b64}'\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "ui/05_media.js is stale: run scripts/build_media.py")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB)")
