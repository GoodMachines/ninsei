"""Write ui/05_media.js: the Lobby's empty-state art, the setup page's hero and the premade person portraits, as
inline WebP data URIs.

The art is generated (gpt-image-2 via Codex): docs/media/src/lobby-art.jpg, and gathering-art.jpg, the scene on the
catalog banner, cropped to the group for the "Welcome to Ninsei" hero. Inline, because Desktop reaches
the backend only through JSON calls, so an <img> can't load it from a plugin route. Hermes's install scanner
reads an inline base64 run that decodes to an image header as media, not as an encoded payload.

The portraits are docs/media/src/presets/pNN.png plus presets.json (an ordered list of {id, alt}). They become
PERSON_PRESETS, 128 px each, one per line so every line starts with a media header for the scanner. A person's
avatar is only the id of one (ninsei_engine/engine.py AV_PRESETS must list the same ids; a test compares them).
Needs ImageMagick with WebP. Usage: python scripts/build_media.py [--check]"""
import base64
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/media/src/lobby-art.jpg"
WELCOME_SRC = ROOT / "docs/media/src/gathering-art.jpg"
WELCOME_CROP = "1086x600+450+170"  # the group under the awning, without the banner's empty left half
WELCOME_WIDTH = 960  # shown at up to 560 css px
PRESETS = ROOT / "docs/media/src/presets"
OUT = ROOT / "ui/05_media.js"
WIDTH = 480  # shown at up to 240 css px, so sharp on 2x screens
PORTRAIT_PX = 128  # the picker's preview is 128 css px; every other place is smaller
PORTRAIT_QUALITY = 70  # about 3.8 KB each: 60 starts to band the hair, 80 costs 22% more with no visible gain


def webp_uri(args: list) -> str:
    webp = subprocess.run(["magick", *args, "-strip", "-define", "webp:method=6", "webp:-"], capture_output=True, check=True).stdout
    return "data:image/webp;base64," + base64.b64encode(webp).decode("ascii")


def presets_js() -> str:
    rows = json.loads((PRESETS / "presets.json").read_text(encoding="utf-8"))
    lines = []
    for r in rows:
        pid, alt = r["id"], r["alt"]
        if not re.fullmatch(r"p\d{2,3}", pid) or not alt.strip() or "'" in alt or "\\" in alt:
            raise SystemExit(f"bad portrait entry in presets.json: {r!r}")
        src = webp_uri([str(PRESETS / (pid + ".png")), "-resize", f"{PORTRAIT_PX}x{PORTRAIT_PX}!", "-quality", str(PORTRAIT_QUALITY)])
        lines.append(f"  {{ id: '{pid}', alt: '{alt}', src: '{src}' }},")
    return ("// The premade person portraits, in the picker's order (docs/media/src/presets/presets.json). A person's avatar is\n"
            "// only the id of one. Each line starts with a WebP data URI, so the install scanner reads it as media.\n"
            "const PERSON_PRESETS = [\n" + "\n".join(lines) + "\n]\n")


def render() -> str:
    lobby = webp_uri([str(SRC), "-resize", f"{WIDTH}x", "-quality", "78"])
    welcome = webp_uri([str(WELCOME_SRC), "-crop", WELCOME_CROP, "+repage", "-resize", f"{WELCOME_WIDTH}x", "-quality", "60"])
    return ("// Generated by scripts/build_media.py from docs/media/src/ (lobby-art.jpg, gathering-art.jpg, presets/). Do not edit.\n"
            "// The Lobby's empty state: the banner's rainy street with nobody there yet but one agent, waiting.\n"
            f"const LOBBY_ART = '{lobby}'\n"
            "// The setup page's hero: the banner's people and their agents, gathered under an awning in the rain.\n"
            f"const WELCOME_ART = '{welcome}'\n\n" + presets_js())


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "ui/05_media.js is stale: run scripts/build_media.py")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB)")
